"""Регламент ведения справочников (FR-016).

Порядок из п. 4.2.16 ТЗ: значение предлагает контент-менеджер, в силу оно
вступает после утверждения администратором, удаление значений не
допускается — дубли объединяются с переносом всех ссылок.

Правила собраны здесь и не обращаются к СУБД, чтобы их можно было проверить
отдельно от маршрутов.
"""

import re

PROPOSED = "proposed"
APPROVED = "approved"
MERGED = "merged"

STATUS_NAMES = {
    PROPOSED: "Предложено",
    APPROVED: "Утверждено",
    MERGED: "Объединено",
}

MAX_NAME_LENGTH = 100
MIN_NAME_LENGTH = 2


def normalize_name(raw: str) -> str:
    """Привести наименование к каноническому виду.

    Убираются крайние пробелы, повторяющиеся пробелы внутри схлопываются.
    Без этого «Экология  и  природопользование» и «Экология и
    природопользование» стали бы разными значениями справочника, а вся
    затея с объединением дублей потеряла бы смысл.
    """
    name = re.sub(r"\s+", " ", raw).strip()
    if len(name) < MIN_NAME_LENGTH:
        raise ValueError(f"Наименование короче {MIN_NAME_LENGTH} символов")
    if len(name) > MAX_NAME_LENGTH:
        raise ValueError(f"Наименование длиннее {MAX_NAME_LENGTH} символов")
    return name


def check_unique(name: str, existing: set[str]) -> None:
    """Проверка отсутствия дубля без учёта регистра.

    Ограничение UNIQUE в базе регистр учитывает, поэтому «Экология» и
    «экология» прошли бы обе. Регламент справочника этого не допускает.
    """
    if name.casefold() in {other.casefold() for other in existing}:
        raise ValueError("Такое значение справочника уже есть")


def check_approve(status: str) -> None:
    """Утвердить можно только предложенное значение."""
    if status == APPROVED:
        raise ValueError("Значение уже утверждено")
    if status == MERGED:
        raise ValueError("Объединённое значение не утверждается")


def check_merge(source_id: int, source_status: str, target_id: int, target_status: str) -> None:
    """Проверка объединения дубля с существующим значением.

    Объединять можно во что-то утверждённое, иначе ссылки перенеслись бы на
    значение, которого формально ещё не существует. Повторное объединение
    уже объединённого запрещено: иначе получится цепочка ссылок, по которой
    невозможно однозначно сказать, где сейчас находятся данные.
    """
    if source_id == target_id:
        raise ValueError("Значение нельзя объединить само с собой")
    if source_status == MERGED:
        raise ValueError("Значение уже объединено с другим")
    if target_status != APPROVED:
        raise ValueError("Объединять можно только с утверждённым значением")
