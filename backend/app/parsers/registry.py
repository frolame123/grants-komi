"""Соответствие источников адаптерам (FR-006).

Перечень источников закрыт (п. 3.2 ТЗ). При обследовании в августе 2026 года
выяснилось, что три источника из четырёх автоматическому разбору не
поддаются, и причины у всех разные. Они зафиксированы здесь, чтобы результат
обследования не потерялся: адаптер каждого такого источника помечает прогон
неуспешным с конкретной причиной, которая попадает в лог и в уведомление
администратору.

Порядок для таких источников установлен п. 4.2.6 ТЗ: карточки заводятся
через модерацию вручную. Механизм реализован в FR-007.

Подробности обследования каждого источника — docs/obsledovanie-istochnikov.md.
Отказ сервера в автоматическом доступе считается решением владельца источника
и не обходится.
"""

from app.parsers import RawProgram
from app.parsers.rkomi import MinEconomAdapter


class SourceUnavailable(RuntimeError):
    """Источник не может быть разобран автоматически."""


class UnavailableAdapter:
    """Адаптер источника, недоступного для автоматического разбора.

    Ничего не делает, кроме объяснения причины. Существует затем, что
    источник из закрытого перечня ТЗ не должен просто исчезнуть из системы:
    он остаётся в списке, опрашивается по расписанию и каждый раз оставляет
    в логе запись о том, почему сведения не собраны.
    """

    def __init__(self, source_name: str, reason: str) -> None:
        self.source_name = source_name
        self.reason = reason

    async def fetch(self) -> list[RawProgram]:
        raise SourceUnavailable(self.reason)


ADAPTERS = {
    "Минэкономразвития Республики Коми": MinEconomAdapter(),
    "Фонд «Агентство регионального развития»": UnavailableAdapter(
        "Фонд «Агентство регионального развития»",
        "домен arrkomi.ru не разрешается ни через провайдера, ни через публичные "
        "серверы имён: сайт источника недоступен. Наполнение — вручную через модерацию",
    ),
    "Цифровая платформа МСП.РФ": UnavailableAdapter(
        "Цифровая платформа МСП.РФ",
        "источник не допускает машинного доступа: запрос данных отвечает 401 "
        "«необходимо авторизоваться» без сессии браузера, карточки мер не "
        "включены в карту сайта. Наполнение — вручную через модерацию (п. 4.2.6 ТЗ)",
    ),
    "Фонд президентских грантов": UnavailableAdapter(
        "Фонд президентских грантов",
        "страницы собираются в браузере скриптами: в разметке 373 символа "
        "видимого текста, карта сайта не публикуется. Наполнение — вручную "
        "через модерацию (п. 4.2.6 ТЗ)",
    ),
}


def adapter_for(source_name: str):
    """Адаптер источника. Неизвестный источник считается недоступным."""
    return ADAPTERS.get(
        source_name,
        UnavailableAdapter(source_name, "адаптер для источника не реализован"),
    )
